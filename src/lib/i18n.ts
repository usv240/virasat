const dict: Record<Lang, Record<string, string>> = { en, hi };

/** Translate a key. Supports {placeholders}. Falls back to English, then the key. */
export function t(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = dict[lang]?.[key] ?? dict.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
  return s;
}

export function speechLang(lang: Lang): string {
  return LANGS.find((l) => l.code === lang)?.speech ?? "en-IN";
}
