/** Return the decision with its family-facing text in the chosen language. */
export function localiseDecision(d: ClaimDecision, lang: Lang): ClaimDecision {
  if (lang !== "hi") return d;
  return {
    ...d,
    routeLabel: ROUTES[d.route] ?? d.routeLabel,
    checklist: d.checklist.map((c: ChecklistItem) => {
      const h = DOCS[c.id];
      return h ? { ...c, label: h.label, what: h.what, where: h.where } : c;
    }),
    notes: NOTES[d.ruleId] ? [...NOTES[d.ruleId], ...(d.notes.some((n) => n.includes("no-objection")) ? [EXTRA_HEIRS] : [])] : d.notes,
  };
}
